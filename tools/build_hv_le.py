#!/usr/bin/env python3
"""Validate and package the source-built HV endian probe; never sign or encrypt it."""

import argparse
import hashlib
import struct
from pathlib import Path

from check_msr_le import read_elf, require, reversed_words


IMAGE_BYTES = 0x1000
CODE_OFFSET = 0x170
RETURN_GATE = bytes.fromhex("08000048 48000008 00000048 4c00012c 4e800420")


def section(path, name, expected_order):
    order, sections, symbols = read_elf(path)
    require(order == expected_order, f"{path}: wrong ELF byte order")
    chosen = sections[name]
    require(not any(s["kind"] in (4, 9) and s["info"] == chosen["index"] and s["data"]
                    for s in sections.values()), f"{path}: payload must have no relocations")
    return chosen["data"], symbols


def check_windows(big, little):
    require(big.endswith(RETURN_GATE) and little.endswith(RETURN_GATE), "missing fixed restoration gate")
    code = bytearray(big[:-len(RETURN_GATE)])
    require(code[8:12] == bytes.fromhex("3aa00000"), "BE fetch marker is not li r21,0")
    code[8:12] = bytes.fromhex("3aa00001")
    require(little == reversed_words(code) + RETURN_GATE, "instruction banks differ beyond their fetch markers")
    words = list(struct.unpack(">" + "I" * (len(code) // 4), code))
    require(words[:2] == [0x4C00012C, 0x7E8000A6], "window must synchronize and read MSR before data")
    require(words[-3:] == [0x7E6903A6, 0x7C0004AC, 0x7DC00164], "window must restore r14's original MSR")
    memory = []
    for offset, word in enumerate(words):
        opcode = word >> 26
        require(opcode != 17, "unexpected system call in HV window")
        if opcode in (16, 18):
            bits = 16 if opcode == 16 else 26
            displacement = word & ((1 << bits) - 4)
            if displacement & (1 << (bits - 1)):
                displacement -= 1 << bits
            require(not word & 3 and 0 <= offset * 4 + displacement < len(code), "branch escapes the window")
        if opcode in range(32, 56) or opcode in (58, 62):
            memory.append(word)
    require(memory == [0x82F00000, 0xA3100000, 0xEB300000, 0x93510000], "unexpected data/stack access in LE window")


def check_payload(payload, symbols, big, little):
    gate = symbols["xsdk_hv_le_gate"]
    be_at = symbols["xsdk_hv_le_big_window"]
    le_at = symbols["xsdk_hv_le_little_window"]
    first, branch = struct.unpack_from(">II", payload, gate)
    require(first == 0x08000048 and branch & 0xFC000003 == 0x48000000, "invalid fetch gate")
    require(gate + 4 + (branch & 0x03FFFFFC) == be_at, "BE gate misses its bank")
    require(gate + 8 == le_at and payload[le_at:le_at + len(little)] == little, "LE gate misses its bank")
    require(payload[be_at:be_at + len(big)] == big, "wrong embedded BE window")
    require(symbols["xsdk_hv_le_payload"] == 0 and symbols["xsdk_hv_le_payload_end"] == len(payload),
            "payload entry/size does not match expansion entry")
    require(payload.count(bytes.fromhex("1122334455667788")) == 1, "missing unique input bytes")


def package(payload):
    padded = payload + bytes((-len(payload)) % 16)
    end = CODE_OFFSET + len(padded)
    require(end <= IMAGE_BYTES, "expansion exceeds one page")
    digest = hashlib.sha256(payload).digest()
    expansion_id = int.from_bytes(digest[:4], "big")
    require(expansion_id not in (0, 0x48565050), "reserved expansion ID")
    image = bytearray(IMAGE_BYTES)
    struct.pack_into(">3I", image, 0, 0x48585052, 0, end)
    struct.pack_into(">4I2Q4I", image, 0x130, expansion_id, 0, 0, 0, 0, 0, 0, 0, 0x160, len(padded) + 0x10)
    struct.pack_into(">3I", image, 0x160, 0x10, 0x10, len(padded))
    image[CODE_OFFSET:end] = padded
    image[0xC:0x20] = hashlib.sha1(image[0x130:end]).digest()
    return bytes(image), expansion_id, digest.hex()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("payload", type=Path)
    parser.add_argument("big", type=Path)
    parser.add_argument("little", type=Path)
    parser.add_argument("image", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    big, _ = section(args.big, ".text.hv_window", ">")
    little, _ = section(args.little, ".text.hv_window", "<")
    payload, symbols = section(args.payload, ".text.hv_payload", ">")
    check_windows(big, little)
    check_payload(payload, symbols, big, little)
    image, expansion_id, digest = package(payload)
    args.image.write_bytes(image)
    args.header.write_text(
        "// Generated by tools/build_hv_le.py.\n"
        "#ifndef XSDK_TEST_HV_LE_IMAGE_H\n#define XSDK_TEST_HV_LE_IMAGE_H\n"
        f"#define HV_LE_IMAGE_BYTES {IMAGE_BYTES}\n#define HV_LE_IMAGE_ID 0x{expansion_id:08X}u\n"
        f'#define HV_LE_IMAGE_SHA256 "{digest}"\n#endif\n', newline="\n")
    print(f"hv_le: PASS relocation-free banks, bounded LE memory accesses, fetch/restore gates; "
          f"unsigned expansion {expansion_id:08X}, {len(payload)} payload bytes")


if __name__ == "__main__":
    main()
