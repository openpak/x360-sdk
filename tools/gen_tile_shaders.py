#!/usr/bin/env python3
"""Generate milestone 44's position pixel shader, which writes the pixel parameters' column and row as its colour, so
tests/probe_tiles.c can see what gl_FragCoord reads under a window offset.

The parameters go in r1, past the one interpolator, with SQ_PROGRAM_CNTL's param_gen and SQ_CONTEXT_MISC's
param_gen_pos and SC_OUTPUT_SCREEN_XY as xost sets them (src/xsc_program.c; xenia:src/xenia/gpu/registers.h:140, 156,
234): their |xy| hold the column and row only with SC_OUTPUT_SCREEN_XY (docs/HARDWARE.md, "Reads at a0, and the pixel
position"). The sign bits are flags, so the shader takes |r1| as max(r1, -r1), then writes |r1| * c0 + c1.

Packed as in tools/gen_hiz_shaders.py, from Xenia's instruction definitions (xenia:src/xenia/gpu/ucode.h) through xost's
encoders and container emitter, and the generator stops unless xost's text assembler gives the same microcode. Prints a
C header with the container, then its disassembly on stderr.
"""

import struct
import sys

import gen_register_shaders as reg
import gen_triangle_shaders as tri
from gen_triangle_shaders import ce, container, enc, xu
from xasm import textasm

PARAMETERS_REGISTER = 1
SCALE_CONSTANT = 0
OFFSET_CONSTANT = 1
PARAM_GEN = 1 << 18
PARAM_GEN_POS_SHIFT = 8
SC_OUTPUT_SCREEN_XY = 1 << 1


def absolute():
    return enc.build_alu(vector_opcode=xu.AluVectorOpcode.kMax, vector_dest=PARAMETERS_REGISTER,
        vector_write_mask=tri.WRITE_XYZW, src1_reg=PARAMETERS_REGISTER, src2_reg=PARAMETERS_REGISTER,
        src2_negate=True, src3_is_temp=True)


def export_position():
    return enc.build_alu(vector_opcode=xu.AluVectorOpcode.kMad, vector_dest=tri.EXPORT_COLOR_0,
        vector_write_mask=tri.WRITE_XYZW, is_export=True, src1_reg=PARAMETERS_REGISTER, src1_is_temp=True,
        src2_reg=SCALE_CONSTANT, src2_is_temp=False, src3_reg=OFFSET_CONSTANT, src3_is_temp=False)


def position_pixel_shader():
    dwords, _ = reg.program([("exec", [absolute()]), ("alloc", tri.ALLOC_COLORS), ("exec", [export_position()])])
    ucode = struct.pack(f">{len(dwords)}I", *dwords)
    r = PARAMETERS_REGISTER
    text = reg.program_text([("exec", [f"max r{r}, r{r}, -r{r}"]), ("alloc",),
        ("exec", [f"mad oC0, r{r}, c{SCALE_CONSTANT}, c{OFFSET_CONSTANT}"])])
    if textasm.assemble_text(text, "pixel") != ucode:
        sys.exit("gen_tile_shaders: the position pixel shader differs from xost's assembly of it")
    return ce.build_container(
        "pixel", ucode, constants=[],
        program_control=tri.program_control(ps_num_reg=r, ps_export_mode=tri.PS_EXPORT_MODE_COLOR) | PARAM_GEN,
        context_misc=tri.CONTEXT_MISC_CENTROIDS_AND_CENTERS | r << PARAM_GEN_POS_SHIFT | SC_OUTPUT_SCREEN_XY,
        interpolators=[ce.Interpolator(tri.EXPORT_INTERPOLATOR_0, ce.USAGE_COLOR, 0)],
        ps_field18=tri.PS_INTERPOLATOR_WORD, creator=tri.CREATOR)


def main():
    print("#ifndef XSDK_TILE_SHADERS_H\n#define XSDK_TILE_SHADERS_H\n\n#include <stdint.h>\n")
    print("// Generated by tools/gen_tile_shaders.py.")
    blob = position_pixel_shader()
    tri.print_array("position_pixel_shader", blob)
    parsed = container.Container(blob)
    print("position_pixel_shader:", file=sys.stderr)
    print(xu.disassemble(parsed.ucode_dwords, parsed.shader_type), file=sys.stderr)
    print("\n#endif")


if __name__ == "__main__":
    main()
